/**
 * Generates docs/TEST_CASES.md from the test sources ("living documentation"):
 * every test is named with a stable ID (TC-… / E2E-…), so the catalogue can't drift from the code.
 *   node scripts/test-catalogue.js
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const LEVELS = [
  ['unit', 'Unit'],
  ['integration', 'Integration / system API'],
  ['chaos', 'Chaos / fault injection'],
  ['e2e', 'End-to-end (browser)'],
];
const TITLE = /(?:\bit|\btest|\]\))(?:\.each\([^)]*\))?\(\s*(['"`])((?:TC|E2E)-[^'"`]+)\1/g;

const technique = (t) => {
  const tags = [];
  if (/\bBVA\b/.test(t)) tags.push('Boundary value analysis');
  if (/\bEP\b|partition \(/.test(t)) tags.push('Equivalence partitioning');
  if (/TC-RBAC/.test(t)) tags.push('Decision table');
  if (/TC-CB-/.test(t)) tags.push('State transition');
  if (/property|TC-HASH-0[789]|TC-CRYPTO-01/.test(t)) tags.push('Property-based');
  if (/TC-MUT-/.test(t)) tags.push('Mutation-driven');
  if (/TC-SEC-|E2E-08|TC-AUTH-07/.test(t)) tags.push('Security');
  if (/TC-CHAOS-|TC-RAFT-(0[5-9]|1[0-5])|TC-NODE-0[56]/.test(t)) tags.push('Fault injection');
  return tags.join(', ') || 'Functional';
};

let md = '# Test case catalogue\n\n_Generated by `node scripts/test-catalogue.js` from the test sources — do not edit by hand._\n\n';
let total = 0;
for (const [dir, label] of LEVELS) {
  const base = path.join(ROOT, 'tests', dir);
  if (!fs.existsSync(base)) continue;
  const files = fs.readdirSync(base).filter((f) => /\.(test|spec)\.js$/.test(f)).sort();
  md += `## ${label}\n\n| ID | Test case | Technique | File |\n| --- | --- | --- | --- |\n`;
  for (const f of files) {
    const src = fs.readFileSync(path.join(base, f), 'utf8');
    for (const m of src.matchAll(TITLE)) {
      const full = m[2].replace(/%[sdo]/g, '…').replace(/\|/g, '\\|');
      const [id, ...rest] = full.split(/[:\s]/);
      md += `| ${id} | ${rest.join(' ').replace(/^[:\s]+/, '').replace(/\s+/g, ' ')} | ${technique(full)} | ${dir}/${f} |\n`;
      total++;
    }
  }
  md += '\n';
}
md += `**${total} named test cases.** Parameterised cases (\`it.each\`) expand to several executed tests each — e.g. the RBAC decision table runs 28 rows and the validation suite runs 69 boundary/partition checks.\n`;
fs.writeFileSync(path.join(ROOT, 'docs', 'TEST_CASES.md'), md);
console.log(`docs/TEST_CASES.md written (${total} named test cases)`);
